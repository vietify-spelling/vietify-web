"""Export the Python rule tables of ../vietify to a JavaScript module.

Run from anywhere:  python tools/export_rules.py [path/to/vietify/src]
The rule tables are data; generating them avoids transcription errors and
keeps the web app in lock-step with the Python reference implementation.
"""
import json
import sys
from pathlib import Path

here = Path(__file__).resolve().parent
src = Path(sys.argv[1]) if len(sys.argv) > 1 else here.parent.parent / "vietify" / "src"
sys.path.insert(0, str(src))

from vietify import (  # noqa: E402
    IPAruleStrong, IPAruleWeak, hepburnRuleStrong, pinyinRuleStrong, pinyinRuleWeak,
)

modules = {
    "IPAruleStrong": IPAruleStrong,
    "IPAruleWeak": IPAruleWeak,
    "hepburnRuleStrong": hepburnRuleStrong,
    "pinyinRuleStrong": pinyinRuleStrong,
    "pinyinRuleWeak": pinyinRuleWeak,
}

out = [
    "// GENERATED by tools/export_rules.py from the Python vietify rule tables.",
    "// Do not edit by hand. Each table is a Map to keep insertion order and",
    "// avoid prototype-key surprises.",
    "",
]
for name, mod in modules.items():
    out.append(f"export const {name} = {{")
    for attr in sorted(vars(mod)):
        if not attr.isupper():
            continue
        value = getattr(mod, attr)
        if isinstance(value, dict):
            items = [
                [list(k) if isinstance(k, tuple) else k, v] for k, v in value.items()
            ]
            out.append(f"  {attr}: new Map({json.dumps(items, ensure_ascii=False)}),")
        else:
            out.append(f"  {attr}: {json.dumps(value, ensure_ascii=False)},")
    out.append("};")
    out.append("")
(here.parent / "public" / "js" / "core" / "rules.generated.js").write_text("\n".join(out), encoding="utf-8")
print("wrote public/js/core/rules.generated.js")


# ---- grammar terminals -------------------------------------------------------
# The parsimonious grammars are PEGs over plain string literals. The JS parsers
# re-implement the rule structure by hand (src/core/*Parser.js) but take every
# literal alternative, in order, from here, so no IPA symbol is ever retyped.
import re  # noqa: E402

LITERAL_RULES = {
    "parser": ["InitialConsonant", "EndingConsonant", "ApprxEndingConsonant",
               "NasalVowel", "Vowel", "Stress", "Glide", "TrueDiphthong"],
    "pinyinParser": ["InitialConsonant", "EndingConsonant", "Vowel", "Glide",
                     "TrueDiphthong"],
}


def rule_literals(grammar_text: str, rule: str) -> list[str]:
    text = re.sub(r"#[^\n]*", "", grammar_text)  # drop comments
    match = re.search(rf"^{rule}\s*=(.*?)(?=^\w+\s*=|\Z)", text, re.S | re.M)
    if not match:
        raise SystemExit(f"rule {rule} not found")
    return re.findall(r'"([^"]*)"', match.group(1))


import importlib  # noqa: E402

out = ["// GENERATED by tools/export_rules.py from the Python parsimonious grammars.",
       "// Literal alternatives of each terminal rule, in grammar (priority) order.", ""]
for module_name, rules in LITERAL_RULES.items():
    module = importlib.import_module(f"vietify.{module_name}")
    # Grammar(...) keeps the source text on the object in `_rules`-less form,
    # so read it back from the module source instead.
    source = Path(module.__file__).read_text(encoding="utf-8")
    grammar_text = re.search(r'Grammar\(r"""(.*?)"""\)', source, re.S).group(1)
    out.append(f"export const {module_name} = {{")
    for rule in rules:
        out.append(f"  {rule}: {json.dumps(rule_literals(grammar_text, rule), ensure_ascii=False)},")
    out.append("};")
    out.append("")
(here.parent / "public" / "js" / "core" / "grammar.generated.js").write_text("\n".join(out), encoding="utf-8")
print("wrote public/js/core/grammar.generated.js")
